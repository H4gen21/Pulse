// Regenerates lib/abi/inheritanceGuard.ts from the Foundry build output.
// Usage: forge build && pnpm abi:gen
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const { abi } = JSON.parse(readFileSync('out/InheritanceGuard.sol/InheritanceGuard.json', 'utf8'));
mkdirSync('lib/abi', { recursive: true });
writeFileSync(
  'lib/abi/inheritanceGuard.ts',
  `// AUTO-GENERATED by scripts/gen-abi.mjs from contracts/InheritanceGuard.sol. Do not edit.\n` +
    `export const inheritanceGuardAbi = ${JSON.stringify(abi, null, 2)} as const;\n`,
);
console.log(`lib/abi/inheritanceGuard.ts: ${abi.length} entries`);
